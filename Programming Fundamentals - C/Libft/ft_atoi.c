#include "libft.h"

int	ft_atoi(const char *nptr)
{
	int		i;
	int		s;
	long	res;

	s = 1;
	res = 0;
	i = 0;
	while (nptr[i] == '\t' || nptr[i] == ' ' || nptr[i] == '\n'
		|| nptr[i] == '\v' || nptr[i] == '\r' || nptr[i] == '\f')
		i++;
	if (nptr[i] == '-' || nptr[i] == '+')
	{
		if (nptr[i] == '-')
			s *= -1;
		i++;
	}
	while (nptr[i] >= '0' && nptr[i] <= '9')
	{
		res = res * 10 +(nptr[i] - '0');
		i++;
	}
	return (res * s);
}
